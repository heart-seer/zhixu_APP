// const 详细案例
//
// const 表示“编译时常量”。
// 简单理解：程序运行之前，值就必须已经确定，并且以后不能修改。

void main() {
  // =====================================================
  // 1. 使用 const 定义基本类型常量
  // =====================================================

  // 圆周率是一个固定的数字，适合使用 const
  const double pi = 3.14159;

  // 一年有固定的月份数量，也可以使用 const
  const int monthsInYear = 12;

  // 固定的文字也可以使用 const
  const String appName = '我的第一个 Dart 程序';

  // 输出常量的值
  print('程序名称：$appName');
  print('圆周率：$pi');
  print('一年有 $monthsInYear 个月');

  // =====================================================
  // 2. const 定义的值不能修改
  // =====================================================

  const country = '中国';
  print('国家：$country');

  // 下面这行代码不能执行，因为 country 是常量
  // country = '美国';

  // 如果取消上面的注释，Dart 会报错：
  // 不能给 const 定义的变量重新赋值。

  // =====================================================
  // 3. const 和 var 的区别
  // =====================================================

  // var 定义的是普通变量，后面可以修改值
  var age = 18;
  print('原来的年龄：$age');

  age = 19;
  print('修改后的年龄：$age');

  // const 定义的是常量，后面不能修改值
  const birthYear = 2000;
  print('出生年份：$birthYear');

  // 下面这行代码不能执行，因为 birthYear 是 const 常量
  // birthYear = 2001;

  // =====================================================
  // 4. const 和 final 的区别
  // =====================================================

  // final 的值只能赋值一次，但是可以在程序运行时确定
  final currentTime = DateTime.now();
  print('当前时间：$currentTime');

  // final 也不能再次赋值
  // currentTime = DateTime.now();

  // const 的值必须在程序运行前就确定
  const fixedNumber = 100;
  print('固定数字：$fixedNumber');

  // 下面的写法不能使用 const，因为 DateTime.now() 需要运行程序后才能获取时间
  // const time = DateTime.now();

  // 简单记忆：
  // const：编译时就确定，不能修改
  // final：运行时确定，但只能赋值一次

  // =====================================================
  // 5. const 定义列表
  // =====================================================

  // const 可以定义一个固定的列表
  const fruits = ['苹果', '香蕉', '橙子'];
  print('水果列表：$fruits');

  // const 列表中的内容也不能修改
  // fruits.add('西瓜');
  // fruits[0] = '葡萄';

  // 如果取消上面的注释，程序会报错，因为 const 列表不能修改。

  // =====================================================
  // 6. const 定义 Map
  // =====================================================

  // Map 可以理解为“键和值”的集合
  const user = {
    'name': '小明',
    'age': 18,
    'city': '北京',
  };

  print('用户姓名：${user['name']}');
  print('用户年龄：${user['age']}');
  print('用户城市：${user['city']}');

  // const Map 中的数据也不能修改
  // user['age'] = 20;

  // =====================================================
  // 7. const 对象案例
  // =====================================================

  // Color 是 Flutter 中常见的类。
  // 在 Flutter 中，经常会看到下面这种写法：
  // const Text('你好');
  // const EdgeInsets.all(16);
  // const SizedBox(height: 20);
  //
  // const 的作用是告诉 Flutter：
  // 这个对象的内容固定，不需要重复创建，可以提高性能。

  // =====================================================
  // 8. 什么时候适合使用 const？
  // =====================================================

  // 适合使用 const 的情况：
  // 1. 固定不变的数字，例如 const pi = 3.14159;
  // 2. 固定不变的文字，例如 const title = '首页';
  // 3. 固定不变的列表或 Map
  // 4. Flutter 中不会变化的界面组件

  // 不适合使用 const 的情况：
  // 1. 值需要运行后才能确定，例如 DateTime.now()
  // 2. 值后面还需要修改，例如计数器 count

  // =====================================================
  // 9. 一个完整的小案例：计算圆的面积
  // =====================================================

  // 半径是固定值，所以可以使用 const
  const double radius = 5.0;

  // 面积的计算结果也是由固定值计算出来的
  // 但是 Dart 中 const 表达式需要使用 const 关键字声明
  const double area = pi * radius * radius;

  print('圆的半径：$radius');
  print('圆的面积：$area');
}
