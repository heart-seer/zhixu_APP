// final 详细案例
//
// final 表示“只能赋值一次的变量”。
// final 的值可以在程序运行时才确定，
// 但是一旦赋值，就不能再次修改。

void main() {
  // =====================================================
  // 1. 使用 final 定义普通变量
  // =====================================================

  // final 变量可以先获取运行时的数据
  final currentTime = DateTime.now();

  // 输出当前时间
  print('当前时间：$currentTime');

  // currentTime 不能再次赋值
  // currentTime = DateTime.now();

  // =====================================================
  // 2. final 和 var 的区别
  // =====================================================

  // var 定义的变量，后面可以修改
  var age = 18;
  print('原来的年龄：$age');

  age = 19;
  print('修改后的年龄：$age');

  // final 定义的变量，只能赋值一次
  final name = '小明';
  print('姓名：$name');

  // 下面的代码不能执行，因为 name 已经有值了
  // name = '小红';

  // =====================================================
  // 3. final 可以先声明，后赋值
  // =====================================================

  // 声明 final 变量时，可以暂时不赋值
  final String message;

  // 第一次给 message 赋值，这是允许的
  message = '欢迎学习 Dart';
  print(message);

  // 第二次赋值不允许
  // message = '欢迎学习 Flutter';

  // =====================================================
  // 4. final 和 const 的区别
  // =====================================================

  // const 的值必须在编译时确定
  const fixedNumber = 100;
  print('const 的值：$fixedNumber');

  // final 的值可以在运行时确定
  final randomNumber = DateTime.now().millisecond;
  print('final 的值：$randomNumber');

  // DateTime.now() 需要程序运行后才能获取时间，
  // 所以不能使用 const，只能使用 final
  final loginTime = DateTime.now();
  print('登录时间：$loginTime');

  // 下面的代码不能使用 const
  // const time = DateTime.now();

  // 简单记忆：
  // const：编译时确定，不能修改
  // final：运行时确定，但只能赋值一次

  // =====================================================
  // 5. final 定义 List
  // =====================================================

  // final List 不能重新指向另一个 List
  final fruits = ['苹果', '香蕉'];
  print('原来的水果：$fruits');

  // final 变量本身不能重新赋值
  // fruits = ['橙子', '西瓜'];

  // 但是，普通 final List 中的内容可以修改
  fruits.add('橙子');
  print('添加水果后：$fruits');

  fruits[0] = '葡萄';
  print('修改水果后：$fruits');

  // 这说明：
  // final 保护的是变量的指向，
  // 不一定保护 List 内部的内容。

  // =====================================================
  // 6. final 定义 Map
  // =====================================================

  // final Map 不能重新指向另一个 Map
  final user = {
    'name': '小明',
    'age': 18,
  };

  print('原来的用户信息：$user');

  // 不能把 user 整体替换成另一个 Map
  // user = {'name': '小红'};

  // 但是，普通 final Map 内部的内容可以修改
  user['age'] = 19;
  user['city'] = '北京';

  print('修改后的用户信息：$user');

  // =====================================================
  // 7. final 实际案例：记录登录用户
  // =====================================================

  // 用户登录后，用户名只需要确定一次
  final loginUser = 'admin';

  // 登录时间在程序运行时获取
  final loginDate = DateTime.now();

  print('登录用户：$loginUser');
  print('登录时间：$loginDate');

  // 登录用户和登录时间都不应该被随意修改，
  // 因此使用 final 比使用 var 更合适。

  // =====================================================
  // 8. final 实际案例：商品价格
  // =====================================================

  // 商品价格从服务器或用户输入中获取，
  // 获取时间是在程序运行时，所以使用 final
  final double price = 99.9;
  final int quantity = 2;

  // totalPrice 是根据固定的价格和数量计算出来的
  final double totalPrice = price * quantity;

  print('商品单价：$price 元');
  print('购买数量：$quantity 件');
  print('商品总价：$totalPrice 元');

  // =====================================================
  // 9. 什么时候适合使用 final？
  // =====================================================

  // 适合使用 final 的情况：
  // 1. 变量只需要赋值一次
  // 2. 值需要运行程序后才能确定
  // 3. 当前时间、随机数、用户信息等
  // 4. 登录用户、订单编号、商品价格等

  // 不适合使用 final 的情况：
  // 1. 变量后面还需要重新赋值
  // 2. 计数器，例如 count++
  // 3. 会不断变化的状态
}
